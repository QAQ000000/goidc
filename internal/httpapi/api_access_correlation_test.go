func TestAPIAccessCorrelationLogAndFiltering(t *testing.T) {
	db, h := testServer(t)
	auditCookie, notificationCookie := apiLogReaders(t, db, h)
	adminID, adminCookie := user(t, db, h, "trace-admin", "super_admin")
	_, customerCookie := user(t, db, h, "trace-customer", "customer")
	supplied := strings.Repeat("a", 32)
	w := requestFrom(h, "GET", "/api/v1/admin/site-settings?secret=never-log-this", nil, "192.0.2.45:1234", adminCookie,
		map[string]string{"X-Request-ID": supplied})
	expect(t, w, http.StatusOK)
	id := w.Header().Get("X-Request-ID")
	if !correlation.Valid(id) || id == supplied {
		t.Fatalf("request ID must be generated by this server, got %q", id)
	}
	var path string
	var status int
	waitAPIAccessLog(t, db, "actor_id=$1 AND correlation_id=$2", adminID, id)
	if err := db.Pool.QueryRow(t.Context(), `SELECT path,status_code FROM admin_api_logs WHERE actor_id=$1 AND correlation_id=$2`, adminID, id).Scan(&path, &status); err != nil {
		t.Fatal(err)
	}
	if path != "/api/v1/admin/site-settings" || status != http.StatusOK {
		t.Fatalf("unexpected access log path=%q status=%d", path, status)
	}
	for _, query := range []string{"correlation_id=" + id, "q=" + id, "username=trace-admin&correlation_id=" + id} {
		filtered := request(h, "GET", "/api/v1/admin/logs/api?"+query, nil, auditCookie, "")
		expect(t, filtered, http.StatusOK)
		page := data(t, filtered)
		items := page["items"].([]any)
		if page["total"].(float64) != 1 || len(items) != 1 || items[0].(map[string]any)["correlation_id"] != id {
			t.Fatalf("correlation lookup did not resolve the original request: %s", filtered.Body.String())
		}
	}
	expect(t, request(h, "GET", "/api/v1/admin/logs/api?correlation_id="+id, nil, notificationCookie, ""), http.StatusForbidden)
	expect(t, request(h, "GET", "/api/v1/admin/logs/api?correlation_id=bad", nil, auditCookie, ""), http.StatusBadRequest)
	// Customer access logs remain excluded even when their exact ID is known.
	customer := request(h, "GET", "/api/v1/me", nil, customerCookie, "")
	expect(t, customer, http.StatusOK)
	waitAPIAccessLog(t, db, "correlation_id=$1", customer.Header().Get("X-Request-ID"))
	filtered := request(h, "GET", "/api/v1/admin/logs/api?correlation_id="+customer.Header().Get("X-Request-ID"), nil, auditCookie, "")
	expect(t, filtered, http.StatusOK)
	if page := data(t, filtered); page["total"].(float64) != 0 || len(page["items"].([]any)) != 0 {
		t.Fatalf("customer log leaked into admin scope: %s", filtered.Body.String())
	}
	// Historical rows have an empty diagnostic origin, not a fabricated ID.
	historical := request(h, "GET", "/api/v1/admin/logs/api?q=navigation-acceptance", nil, auditCookie, "")
	expect(t, historical, http.StatusOK)
	if item := data(t, historical)["items"].([]any)[0].(map[string]any); item["correlation_id"] != "" {
		t.Fatalf("historical access log acquired an invented correlation: %#v", item)
	}
}

func TestAPIAccessLogSurvivesRequestCancellation(t *testing.T) {
	db, h := testServer(t)
	actor, cookie := user(t, db, h, "canceled-access", "customer")
	id := strings.Repeat("b", 32)
	ctx, cancel := context.WithCancel(correlation.WithID(t.Context(), id))
	defer cancel()
	r := httptest.NewRequest("GET", "/api/v1/canceled-fixture?token=hidden", nil).WithContext(ctx)
	r.Header.Set("Cookie", cookie)
	r.RemoteAddr = "192.0.2.21:1234"
	w := httptest.NewRecorder()
	s := &Server{db: db, log: slog.New(slog.NewTextHandler(io.Discard, nil))}
	startTestAccessLogging(t, s)
	s.authWith(func(w http.ResponseWriter, r *http.Request) {
		cancel()
		w.WriteHeader(http.StatusNoContent)
	}, false, false)(w, r)
	if w.Code != http.StatusNoContent {
		t.Fatalf("response status=%d", w.Code)
	}
	var logged bool
	waitAPIAccessLog(t, db, "actor_id=$1 AND correlation_id=$2 AND path='/api/v1/canceled-fixture' AND status_code=204", actor, id)
	if err := db.Pool.QueryRow(t.Context(), `SELECT EXISTS(SELECT 1 FROM admin_api_logs WHERE actor_id=$1 AND correlation_id=$2 AND path='/api/v1/canceled-fixture' AND status_code=204)`, actor, id).Scan(&logged); err != nil || !logged {
		t.Fatalf("request cancellation erased access diagnostic: logged=%v err=%v", logged, err)
	}
}
